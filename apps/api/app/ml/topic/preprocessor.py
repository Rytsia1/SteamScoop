ALL_TOPIC_STOP_WORDS: set[str] = ENGLISH_STOP_WORDS | STEAM_DOMAIN_STOP_WORDS


class TopicPreprocessor:
    """Preprocesses Steam reviews into filtered token streams for topic models."""

    def __init__(self, additional_stop_words: set[str] | None = None) -> None:
        self.stop_words = ALL_TOPIC_STOP_WORDS | (additional_stop_words or set())
        self.word_pattern = re.compile(r"(?u)\b[a-zA-Z]{3,}\b")

    def tokenize(self, text: str) -> list[str]:
        """Convert raw text into normalized, stop-word filtered word tokens."""
        lower = text.lower()
        tokens = self.word_pattern.findall(lower)
        return [t for t in tokens if t not in self.stop_words]

    def preprocess_to_text(self, text: str) -> str:
        """Tokenize and rejoin into cleaned space-separated string for vectorizers."""
        tokens = self.tokenize(text)
        return " ".join(tokens)


# Alias for explicit naming
TopicTextPreprocessor = TopicPreprocessor
