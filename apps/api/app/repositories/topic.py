"""Repository for topic taxonomy and review-level topic assignments."""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from decimal import Decimal
from typing import Any

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.topic import ReviewTopic, Topic
from app.repositories.base import BaseRepository


class TopicRepository(BaseRepository[Topic]):
    """Data access repository for Topic definitions and ReviewTopic assignments."""

    def __init__(self, session: Session) -> None:
        super().__init__(Topic, session)

    def get_by_key(self, ml_model_id: uuid.UUID, topic_key: str) -> Topic | None:
        """Fetch topic definition by its model ID and stable machine key."""
        stmt = select(Topic).where(
            Topic.ml_model_id == ml_model_id,
            Topic.topic_key == topic_key,
        )
        return self.session.scalars(stmt).first()

    def get_topics_by_model(
        self,
        ml_model_id: uuid.UUID,
        include_outliers: bool = True,
    ) -> Sequence[Topic]:
        """Fetch all topics generated by a specific MLModel."""
        stmt = select(Topic).where(Topic.ml_model_id == ml_model_id)
        if not include_outliers:
            stmt = stmt.where(Topic.is_outlier.is_(False))
        stmt = stmt.order_by(Topic.topic_key)
        return self.session.scalars(stmt).all()

    def create_topic(
        self,
        ml_model_id: uuid.UUID,
        topic_key: str,
        label: str,
        keywords: list[str],
        representative_terms: list[Any],
        description: str | None = None,
        is_outlier: bool = False,
    ) -> Topic:
        """Create or update a topic definition enforcing idempotency on (ml_model_id, topic_key)."""
        stmt = select(Topic).where(
            Topic.ml_model_id == ml_model_id,
            Topic.topic_key == topic_key,
        )
        existing = self.session.scalars(stmt).first()

        if existing:
            existing.label = label
            existing.description = description
            existing.keywords = keywords
            existing.representative_terms = representative_terms
            existing.is_outlier = is_outlier
            self.session.flush()
            return existing

        topic = Topic(
            ml_model_id=ml_model_id,
            topic_key=topic_key,
            label=label,
            description=description,
            keywords=keywords,
            representative_terms=representative_terms,
            is_outlier=is_outlier,
        )
        self.session.add(topic)
        self.session.flush()
        return topic

    def bulk_create_topics(self, topics_data: list[dict[str, Any]]) -> list[Topic]:
        """Persist a batch of topics with transactional safety."""
        created: list[Topic] = []
        for t in topics_data:
            topic = self.create_topic(
                ml_model_id=t["ml_model_id"],
                topic_key=t["topic_key"],
                label=t["label"],
                keywords=t.get("keywords", []),
                representative_terms=t.get("representative_terms", []),
                description=t.get("description"),
                is_outlier=bool(t.get("is_outlier", False)),
            )
            created.append(topic)
        self.session.commit()
        return created

    def assign_review_topic(
        self,
        review_id: uuid.UUID,
        topic_id: uuid.UUID,
        pipeline_run_id: uuid.UUID,
        score: float | None = None,
        is_primary: bool = False,
    ) -> ReviewTopic:
        """Create or update a review topic assignment enforcing idempotency."""
        stmt = select(ReviewTopic).where(
            ReviewTopic.review_id == review_id,
            ReviewTopic.topic_id == topic_id,
            ReviewTopic.pipeline_run_id == pipeline_run_id,
        )
        existing = self.session.scalars(stmt).first()

        score_decimal = Decimal(f"{score:.7f}") if score is not None else None

        if existing:
            existing.score = score_decimal
            existing.is_primary = is_primary
            self.session.flush()
            return existing

        assignment = ReviewTopic(
            review_id=review_id,
            topic_id=topic_id,
            pipeline_run_id=pipeline_run_id,
            score=score_decimal,
            is_primary=is_primary,
        )
        self.session.add(assignment)
        self.session.flush()
        return assignment

    def bulk_assign_review_topics(
        self,
        assignments_data: list[dict[str, Any]],
    ) -> list[ReviewTopic]:
        """Persist a batch of review topic assignments with transactional safety."""
        created: list[ReviewTopic] = []
        for d in assignments_data:
            assignment = self.assign_review_topic(
                review_id=d["review_id"],
                topic_id=d["topic_id"],
                pipeline_run_id=d["pipeline_run_id"],
                score=d.get("score"),
                is_primary=bool(d.get("is_primary", False)),
            )
            created.append(assignment)
        self.session.commit()
        return created

    def get_review_topics_by_review(
        self,
        review_id: uuid.UUID,
        pipeline_run_id: uuid.UUID | None = None,
    ) -> Sequence[ReviewTopic]:
        """Fetch all topic assignments for a review."""
        stmt = select(ReviewTopic).where(ReviewTopic.review_id == review_id)
        if pipeline_run_id:
            stmt = stmt.where(ReviewTopic.pipeline_run_id == pipeline_run_id)
        return self.session.scalars(stmt).all()

    def get_review_topics_by_topic(
        self,
        topic_id: uuid.UUID,
        limit: int = 100,
    ) -> Sequence[ReviewTopic]:
        """Fetch review assignments for a specific topic."""
        stmt = (
            select(ReviewTopic)
            .where(ReviewTopic.topic_id == topic_id)
            .order_by(ReviewTopic.score.desc().nullslast())
            .limit(limit)
        )
        return self.session.scalars(stmt).all()
