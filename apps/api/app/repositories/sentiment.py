"""Repository for versioned review-level sentiment predictions."""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from decimal import Decimal
from typing import Any

from sqlalchemy import select, update
from sqlalchemy.orm import Session

from app.models.sentiment import SentimentPrediction
from app.repositories.base import BaseRepository


class SentimentRepository(BaseRepository[SentimentPrediction]):
    """Data access repository for SentimentPrediction records with version and currency tracking."""

    def __init__(self, session: Session) -> None:
        super().__init__(SentimentPrediction, session)

    def get_current_for_review(self, review_id: uuid.UUID) -> SentimentPrediction | None:
        """Fetch the currently active sentiment prediction for a review."""
        stmt = select(SentimentPrediction).where(
            SentimentPrediction.review_id == review_id,
            SentimentPrediction.is_current.is_(True),
        )
        return self.session.scalars(stmt).first()

    def create_prediction(
        self,
        review_id: uuid.UUID,
        ml_model_id: uuid.UUID,
        pipeline_run_id: uuid.UUID,
        label: str,
        confidence: float | None = None,
        probabilities: dict[str, Any] | None = None,
        is_current: bool = True,
    ) -> SentimentPrediction:
        """Create or update a sentiment prediction enforcing idempotency."""
        # 1. Manage is_current flag to protect partial unique index
        if is_current:
            # Unset any currently active prediction for this review
            self.session.execute(
                update(SentimentPrediction)
                .where(
                    SentimentPrediction.review_id == review_id,
                    SentimentPrediction.is_current.is_(True),
                )
                .values(is_current=False)
            )

        # 2. Check if prediction already exists for this exact (review, model, run) tuple
        stmt = select(SentimentPrediction).where(
            SentimentPrediction.review_id == review_id,
            SentimentPrediction.ml_model_id == ml_model_id,
            SentimentPrediction.pipeline_run_id == pipeline_run_id,
        )
        existing = self.session.scalars(stmt).first()

        conf_decimal = Decimal(f"{confidence:.5f}") if confidence is not None else None

        if existing:
            existing.label = label
            existing.confidence = conf_decimal
            existing.probabilities = probabilities or {}
            existing.is_current = is_current
            self.session.flush()
            return existing

        prediction = SentimentPrediction(
            review_id=review_id,
            ml_model_id=ml_model_id,
            pipeline_run_id=pipeline_run_id,
            label=label,
            confidence=conf_decimal,
            probabilities=probabilities or {},
            is_current=is_current,
        )
        self.session.add(prediction)
        self.session.flush()
        return prediction

    def bulk_create_predictions(
        self,
        predictions_data: list[dict[str, Any]],
        set_current: bool = True,
    ) -> list[SentimentPrediction]:
        """Persist a batch of sentiment predictions with transactional safety."""
        created: list[SentimentPrediction] = []
        for d in predictions_data:
            pred = self.create_prediction(
                review_id=d["review_id"],
                ml_model_id=d["ml_model_id"],
                pipeline_run_id=d["pipeline_run_id"],
                label=d["label"],
                confidence=d.get("confidence"),
                probabilities=d.get("probabilities"),
                is_current=d.get("is_current", set_current),
            )
            created.append(pred)
        self.session.commit()
        return created

    def get_predictions_for_run(
        self,
        pipeline_run_id: uuid.UUID,
    ) -> Sequence[SentimentPrediction]:
        """Fetch all sentiment predictions generated by a specific pipeline run."""
        stmt = select(SentimentPrediction).where(
            SentimentPrediction.pipeline_run_id == pipeline_run_id
        )
        return self.session.scalars(stmt).all()

    def get_predictions_by_model(
        self,
        ml_model_id: uuid.UUID,
        limit: int = 1000,
    ) -> Sequence[SentimentPrediction]:
        """Fetch predictions generated by a specific ML model version."""
        stmt = (
            select(SentimentPrediction)
            .where(SentimentPrediction.ml_model_id == ml_model_id)
            .order_by(SentimentPrediction.predicted_at.desc())
            .limit(limit)
        )
        return self.session.scalars(stmt).all()
