import uuid
from datetime import UTC, datetime
from decimal import Decimal
from typing import TYPE_CHECKING, Any

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.session import Base

if TYPE_CHECKING:
    from app.models.ml import MLModel, PipelineRun
    from app.models.review import Review


class Topic(Base):
    """Versioned topic taxonomy generated by a topic modeling pipeline."""

    __tablename__ = "topic"
    __table_args__ = (
        UniqueConstraint("ml_model_id", "topic_key", name="uq_topic_model_topic_key"),
        CheckConstraint(
            "jsonb_typeof(keywords) = 'array'",
            name="ck_topic_keywords_is_array",
        ),
        CheckConstraint(
            "jsonb_typeof(representative_terms) = 'array'",
            name="ck_topic_representative_terms_is_array",
        ),
        Index("ix_topic_model_outlier", "ml_model_id", "is_outlier"),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    ml_model_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("ml_model.id", ondelete="RESTRICT", name="fk_topic_ml_model_id"),
        nullable=False,
    )
    topic_key: Mapped[str] = mapped_column(String(100), nullable=False)
    label: Mapped[str] = mapped_column(String(180), nullable=False)
    description: Mapped[str | None] = mapped_column(Text, nullable=True)

    keywords: Mapped[list[Any]] = mapped_column(
        JSONB, nullable=False, default=list, server_default=func.json_build_array()
    )
    representative_terms: Mapped[list[Any]] = mapped_column(
        JSONB, nullable=False, default=list, server_default=func.json_build_array()
    )

    is_outlier: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default="false"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
    )

    # Relationships
    ml_model: Mapped["MLModel"] = relationship("MLModel", back_populates="topics")
    review_topics: Mapped[list["ReviewTopic"]] = relationship("ReviewTopic", back_populates="topic")

    def __repr__(self) -> str:
        return f"<Topic(id={self.id}, topic_key='{self.topic_key}', label='{self.label}')>"


class ReviewTopic(Base):
    """Associates a review with a versioned topic output."""

    __tablename__ = "review_topic"
    __table_args__ = (
        UniqueConstraint(
            "review_id", "topic_id", "pipeline_run_id", name="uq_review_topic_review_topic_run"
        ),
        CheckConstraint(
            "score IS NULL OR (score BETWEEN 0 AND 1)",
            name="ck_review_topic_score",
        ),
        Index("ix_review_topic_topic_created", "topic_id", "created_at"),
        Index("ix_review_topic_review_run", "review_id", "pipeline_run_id"),
        Index(
            "ix_review_topic_primary",
            "review_id",
            "pipeline_run_id",
            unique=True,
            postgresql_where=text("is_primary = TRUE"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    review_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("review.id", ondelete="RESTRICT", name="fk_review_topic_review_id"),
        nullable=False,
    )
    topic_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("topic.id", ondelete="RESTRICT", name="fk_review_topic_topic_id"),
        nullable=False,
    )
    pipeline_run_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey(
            "pipeline_run.id",
            ondelete="RESTRICT",
            name="fk_review_topic_pipeline_run_id",
        ),
        nullable=False,
    )

    score: Mapped[Decimal | None] = mapped_column(Numeric(8, 7), nullable=True)
    is_primary: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default="false"
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(UTC),
        server_default=func.now(),
    )

    # Relationships
    review: Mapped["Review"] = relationship("Review", back_populates="review_topics")
    topic: Mapped["Topic"] = relationship("Topic", back_populates="review_topics")
    pipeline_run: Mapped["PipelineRun"] = relationship(
        "PipelineRun", back_populates="review_topics"
    )

    def __repr__(self) -> str:
        return f"<ReviewTopic(id={self.id}, review_id={self.review_id}, topic_id={self.topic_id})>"
